import { relations, sql } from 'drizzle-orm'
import {
  check,
  date,
  doublePrecision,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  index,
} from 'drizzle-orm/pg-core'

import { generateUUID } from './utils/uuid'

/**
 * Item Type Enumeration
 * - layer: Outerwear items like jackets, coats, or sweaters worn over other clothing
 * - top: Upper body garments like shirts, t-shirts, or blouses
 * - bottom: Lower body garments like pants, shorts, or skirts
 * - footwear: Shoes, boots, sandals, or other foot coverings
 * - accessory: Supplementary items like bags, jewelry, or hats
 */
export const itemTypeEnum: [string, ...string[]] = [
  'layer',
  'top',
  'bottom',
  'footwear',
  'accessory',
]
export const itemTypeEnumPg = pgEnum('itemType', itemTypeEnum)

/**
 * Item Status Enumeration
 * - available: Item is active and can be included in outfit suggestions
 * - withheld: Item is temporarily excluded from outfit suggestions but not permanently removed
 * - retired: Item is permanently removed from the wardrobe and no longer used
 */
export const itemStatusEnum: [string, ...string[]] = [
  'available',
  'withheld',
  'retired',
]
export const itemStatusEnumPg = pgEnum('itemStatus', itemStatusEnum)

/**
 * Item
 */
export const item = pgTable('item', {
  id: text('id')
    .$defaultFn(() => generateUUID())
    .primaryKey(),
  name: text('name').notNull(),
  brand: text('brand'),
  type: itemTypeEnumPg('type').notNull(),
  status: itemStatusEnumPg('status').notNull().default('available'),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
  userId: text('user_id').notNull(),
})

export const itemRelations = relations(item, ({ many }) => ({
  outfitItems: many(outfitItem),
}))

/**
 * Outfit
 */
export const outfit = pgTable(
  'outfit',
  {
    id: text('id')
      .$defaultFn(() => generateUUID())
      .primaryKey(),
    rating: smallint('rating').notNull(),
    wearDate: date('wear_date', { mode: 'date' }),
    locationLatitude: doublePrecision('location_latitude'),
    locationLongitude: doublePrecision('location_longitude'),
    userId: text('user_id').notNull(),
  },
  (table) => [
    check('rating_check', sql`${table.rating} >= 0 AND ${table.rating} <= 2`),
  ]
)

export const outfitRelations = relations(outfit, ({ many }) => ({
  outfitItems: many(outfitItem),
  outfitTags: many(outfitTag),
}))

/**
 * Outfit Item
 */
export const outfitItem = pgTable(
  'outfit_item',
  {
    outfitId: text('outfit_id')
      .notNull()
      .references(() => outfit.id, { onDelete: 'cascade' }),
    itemId: text('item_id')
      .notNull()
      .references(() => item.id, { onDelete: 'cascade' }),
    itemType: itemTypeEnumPg('item_type').notNull(),
  },
  (table) => [primaryKey({ columns: [table.outfitId, table.itemId] })]
)

export const outfitItemRelations = relations(outfitItem, ({ one }) => ({
  outfit: one(outfit, {
    fields: [outfitItem.outfitId],
    references: [outfit.id],
  }),
  item: one(item, {
    fields: [outfitItem.itemId],
    references: [item.id],
  }),
}))

/**
 * Tag Status Enumeration
 * - manually_assigned: Tag was explicitly added by the user to the outfit
 * - suggested: Tag was automatically suggested by the system but not yet reviewed
 * - suggestion_accepted: User accepted a system-suggested tag
 * - suggestion_rejected: User rejected a system-suggested tag
 */
export const tagStatusEnum: [string, ...string[]] = [
  'manually_assigned',
  'suggested',
  'suggestion_accepted',
  'suggestion_rejected',
]
export const tagStatusEnumPg = pgEnum('tagStatus', tagStatusEnum)

/**
 * Tag
 */
export const tag = pgTable('tag', {
  id: text('id')
    .$defaultFn(() => generateUUID())
    .primaryKey(),
  name: text('name').notNull(),
  hexColor: text('hex_color').notNull(),
  createdAt: timestamp('created_at').notNull().defaultNow(),
  userId: text('user_id').notNull(),
})

export const tagRelations = relations(tag, ({ many }) => ({
  outfitTags: many(outfitTag),
}))

/**
 * Outfit Tag
 */
export const outfitTag = pgTable(
  'outfit_tag',
  {
    outfitId: text('outfit_id')
      .notNull()
      .references(() => outfit.id, { onDelete: 'cascade' }),
    tagId: text('tag_id')
      .notNull()
      .references(() => tag.id, { onDelete: 'cascade' }),
    status: tagStatusEnumPg('status').notNull().default('suggested'),
  },
  (table) => [primaryKey({ columns: [table.outfitId, table.tagId] })]
)

export const outfitTagRelations = relations(outfitTag, ({ one }) => ({
  outfit: one(outfit, {
    fields: [outfitTag.outfitId],
    references: [outfit.id],
  }),
  tag: one(tag, {
    fields: [outfitTag.tagId],
    references: [tag.id],
  }),
}))

/**
 * Agent Role Enumeration
 * - system: System message providing context or instructions to the agent
 * - user: Message from the user in the conversation
 * - assistant: Response generated by the AI agent
 * - tool: Message representing a tool call or tool result
 */
export const agentRoleEnum: [string, ...string[]] = [
  'system',
  'user',
  'assistant',
  'tool',
]
export const agentRoleEnumPg = pgEnum('agentRole', agentRoleEnum)

/**
 * Finish Reason Enumeration
 * - stop: Model completed generation normally (reached a natural stopping point)
 * - length: Generation stopped because maximum token limit was reached
 * - tool_calls: Generation stopped to allow tool calls to be executed
 * - content_filter: Generation stopped due to content filtering policies
 * - error: Generation stopped due to an error during processing
 * - other: Generation stopped for a reason not covered by other categories
 */
export const finishReasonEnum: [string, ...string[]] = [
  'stop',
  'length',
  'tool_calls',
  'content_filter',
  'error',
  'other',
]
export const finishReasonEnumPg = pgEnum('finishReason', finishReasonEnum)

/**
 * Agent Conversation
 */
export const agentConversation = pgTable('agent_conversation', {
  id: text('id')
    .$defaultFn(() => generateUUID())
    .primaryKey(),
  userId: text('user_id').notNull(),
  title: text('title'),
  systemPrompt: text('system_prompt'),
  model: text('model').notNull(),
  leafMessageId: text('leaf_message_id'),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
  archivedAt: timestamp('archived_at', { withTimezone: true }),
})

/**
 * Agent Message
 */
export const agentMessage = pgTable(
  'agent_message',
  {
    id: text('id')
      .$defaultFn(() => generateUUID())
      .primaryKey(),
    conversationId: text('conversation_id')
      .notNull()
      .references(() => agentConversation.id, { onDelete: 'cascade' }),
    parentId: text('parent_id'),
    role: agentRoleEnumPg('role').notNull(),
    parts: jsonb('parts').notNull(),
    metadata: jsonb('metadata'),
    model: text('model').notNull(),
    usage: jsonb('usage'),
    finishReason: finishReasonEnumPg('finish_reason').notNull(),
    error: jsonb('error'),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (table) => [
    index('agent_message_conversation_idx').on(table.conversationId),
    index('agent_message_parent_idx').on(table.parentId),
    index('agent_message_convo_created_idx').on(
      table.conversationId,
      table.createdAt
    ),
  ]
)

export const agentConversationRelations = relations(
  agentConversation,
  ({ many, one }) => ({
    messages: many(agentMessage),
    leafMessage: one(agentMessage, {
      fields: [agentConversation.leafMessageId],
      references: [agentMessage.id],
    }),
  })
)

export const agentMessageRelations = relations(agentMessage, ({ one, many }) => ({
  conversation: one(agentConversation, {
    fields: [agentMessage.conversationId],
    references: [agentConversation.id],
  }),
  parent: one(agentMessage, {
    fields: [agentMessage.parentId],
    references: [agentMessage.id],
    relationName: 'parent',
  }),
  children: many(agentMessage, {
    relationName: 'parent',
  }),
}))

